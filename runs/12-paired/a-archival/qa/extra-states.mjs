import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
const base=resolve(import.meta.dirname,'../..');
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
for(const [folder,port] of [['a-archival',4311],['b-poster',4312]]){
 const ctx=await browser.newContext({viewport:{width:375,height:812}}),page=await ctx.newPage(),errors=[],lines=[];
 page.on('pageerror',e=>errors.push(e.message));
 const go=p=>page.goto(`http://localhost:${port}${p}`,{waitUntil:'networkidle'});
 await go('/subscriptions/build');
 await page.locator('[name=plan][value=trio]').check();
 for(const id of ['sylhet-black','assam-gold','ilam-green'])await page.locator(`[name=tea][value=${id}]`).check();
 assert(await page.locator('[data-builder-submit]').isEnabled());
 assert.match(await page.locator('[data-plan-price]').textContent(),/34.00/);
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('[name=tea]:checked').count(),3);
 await page.locator('[data-builder-submit]').click();await page.waitForURL('**/checkout');await page.waitForLoadState('networkidle');
 assert.match(await page.locator('[data-total]').textContent(),/34.00/);
 lines.push('PASS three-pouch plan: exact tea count, $34.00 total, selection persists after reload.');
 await go('/cart');await page.locator('[data-remove]').click();
 assert(await page.locator('[data-empty]').isVisible());
 assert.equal(await page.evaluate(()=>document.activeElement.closest('[data-empty]')!==null),true);
 await page.reload({waitUntil:'networkidle'});assert(await page.locator('[data-empty]').isVisible());
 lines.push('PASS cart removal: final line removed, empty state survives reload, focus moves to browse link.');
 await page.evaluate(()=>localStorage.setItem('ll-cart-v1','{"bad":true}'));
 await go('/cart');
 assert(await page.locator('[data-storage-error]').isVisible());assert(await page.locator('[data-empty]').isVisible());
 await go('/tea/sylhet-black');await page.locator('[data-add]').click();await page.waitForTimeout(180);
 await go('/cart');assert.equal(await page.locator('[data-quantity]').count(),1);await page.reload({waitUntil:'networkidle'});
 assert(await page.locator('[data-storage-error]').isHidden());
 lines.push('PASS corrupt cart recovery: safe empty state, explicit warning, valid subsequent save and reload.');
 await page.route('**/assets/*.svg',route=>route.abort());
 await go('/tea/assam-gold');
 assert(await page.locator('.image-fallback').first().isVisible());
 assert(await page.locator('[data-add]').isEnabled());
 lines.push('PASS image-error fallback: explanation is visible and purchase control remains usable.');
 assert.equal(errors.length,0,errors.join('\n'));
 lines.push('Console errors: 0.','PASS extra frontend states.');
 const text=lines.join('\n')+'\n';
 writeFileSync(resolve(base,folder,'qa/extra-states.txt'),text);
 console.log(folder+'\n'+text);
 await ctx.close();
}
await browser.close();
