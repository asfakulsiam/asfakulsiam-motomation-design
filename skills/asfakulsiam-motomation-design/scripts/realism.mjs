#!/usr/bin/env node
// Content realism (v3.0.0, part of gate axis X): does the customer-facing content read like a real product?
// Static and zero-dependency. It reads the text a visitor sees (HTML and JSX text nodes, alt/title/aria-label/placeholder
// attributes, string values in data/*.json) and fails on what makes a build look unfinished or dishonest:
//   leak     internal process notes in customer copy: TODO, TBD, FIXME, lorem ipsum, "placeholder text", the brief,
//            checkpoints, DESIGN.md, archetype, signature move, collision draw, gate output
//   generic  sequential or template fixture names: "Product 1", "Item 2", "Card title", "Category A", John Doe, Acme
//   repeat   one fixture shipped many times: in a data array of 6+ records, duplicated names or titles (> 25%), every
//            price identical, or duplicated descriptions (> 50%)
//   dead     a control that goes nowhere: href="#", href="", href="javascript:…"
// Warnings (never fail): [NEEDS COPY] markers left for the client, one long sentence repeated 4+ times in markup.
// Usage: node scripts/realism.mjs <project-dir> [--json]   Exit: 0 clean · 1 problems · 2 usage.
import { readFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const SKIP_DIR = /^(node_modules|out|dist|build|\.next|\.git|frames|frames-mobile|coverage)$/;
const CODE = /\.(html?|tsx|jsx|astro|vue|svelte|mdx)$/;
function walk(dir, out = [], depth = 0) {
  if (depth > 10 || !existsSync(dir)) return out;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith(".") || SKIP_DIR.test(e.name)) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, out, depth + 1); else out.push(p);
  }
  return out;
}
const stripComments = (s) => s
  .replace(/<!--[\s\S]*?-->/g, " ")
  .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, " ")
  .replace(/\/\*[\s\S]*?\*\//g, " ")
  .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, " ")
  .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, " ")
  .replace(/(^|[^:"'`])\/\/[^\n]*/g, "$1");
// visible text: text nodes between tags, plus the attributes a visitor or assistive tech reads
export function visibleText(src) {
  const s = stripComments(src); const out = [];
  for (const m of s.matchAll(/>([^<>{}]+)</g)) { const t = m[1].replace(/\s+/g, " ").trim(); if (t && /[a-z]/i.test(t)) out.push(t); }
  for (const m of s.matchAll(/\b(?:alt|title|aria-label|placeholder|content)\s*=\s*(?:"([^"]*)"|'([^']*)'|\{\s*"([^"]*)"\s*\})/g)) { const t = (m[1] ?? m[2] ?? m[3] ?? "").trim(); if (t) out.push(t); }
  return out;
}
const LEAK = [
  [/\blorem ipsum\b|\bdolor sit amet\b/i, "lorem ipsum"],
  [/\bTODO\b|\bFIXME\b|\bTBD\b|\bXXX\b/, "a TODO / TBD / FIXME marker"],
  [/\bplaceholder (?:text|copy|content|image|name)\b|\byour (?:text|headline|tagline) here\b|\binsert (?:text|copy|image)\b/i, "placeholder wording"],
  [/\b(?:the|this) brief\b|\bper the brief\b|\bclient brief\b/i, "the brief mentioned to customers"],
  [/\bcheckpoint [1-6]\b|\bthinking sequence\b|\bdelivery gate\b|\bgate\.mjs\b|\bDESIGN\.md\b|\bMOTION\.md\b|\bSCHEMA\.md\b/i, "a process or file name from the build"],
  [/\barchetype\b|\bsignature move\b|\bcollision (?:draw|engine)\b|\bmutation operator\b|\bmotomation (?:plan|stamp|gate|checkpoint)\b/i, "skill vocabulary"],
  [/\bas an ai\b|\bgenerated by (?:ai|an ai|chatgpt|claude)\b/i, "an AI disclaimer"],
];
const GENERIC = /\b(?:(?:Product|Item|Card|Category|Feature|Service|Project|Article|Post|Listing|Course|Room|Plan|Tier)\s(?:\d{1,2}|[A-H])|Card title|Section title|Sample (?:product|item|text)|John Doe|Jane Doe|Acme(?: Corp| Inc)?|Lorem Corp|Company Name|Brand Name)\b/;
const DEAD = /\bhref\s*=\s*(?:"(?:#|javascript:[^"]*)?"|'(?:#|javascript:[^']*)?'|\{\s*"#"\s*\})/g;

function records(json, out = []) {
  if (Array.isArray(json)) { if (json.length >= 6 && json.every((x) => x && typeof x === "object" && !Array.isArray(x))) out.push(json); json.forEach((x) => records(x, out)); }
  else if (json && typeof json === "object") Object.values(json).forEach((v) => records(v, out));
  return out;
}
const dupShare = (vals) => { const v = vals.filter((x) => typeof x === "string" && x.trim()).map((x) => x.trim().toLowerCase()); if (v.length < 6) return 0; return 1 - new Set(v).size / v.length; };
function jsonStrings(j, out = []) { if (typeof j === "string") out.push(j); else if (Array.isArray(j)) j.forEach((x) => jsonStrings(x, out)); else if (j && typeof j === "object") for (const [k, v] of Object.entries(j)) if (!/^(id|slug|href|src|url|image|img|icon|sku|key|type|entity|kind|status|currency|locale|color|colour)$/i.test(k)) jsonStrings(v, out); return out; }

export function realism(target) {
  const root = resolve(target); const problems = []; const warnings = [];
  if (!existsSync(root) || !statSync(root).isDirectory()) return { error: `not a directory: ${target}` };
  const rel = (p) => relative(root, p).split(sep).join("/");
  const files = walk(root);
  const add = (list, kind, file, what) => { if (list.length < 40) list.push({ kind, file: rel(file), what }); };
  const longLines = new Map();
  for (const f of files.filter((f) => CODE.test(f) && !/(^|\/)(scripts|tests?|__tests__)\//.test(rel(f)))) {
    let src; try { src = readFileSync(f, "utf8"); } catch { continue; }
    const texts = visibleText(src);
    for (const t of texts) {
      for (const [re, label] of LEAK) if (re.test(t)) { add(problems, "leak", f, `${label}: "${t.slice(0, 70)}"`); break; }
      const g = GENERIC.exec(t); if (g) add(problems, "generic", f, `template fixture "${g[0]}" in "${t.slice(0, 60)}"`);
      if (/\[NEEDS COPY\]/.test(t)) add(warnings, "needs-copy", f, `[NEEDS COPY] left for the client: "${t.slice(0, 60)}"`);
      if (t.length >= 40) longLines.set(t, (longLines.get(t) || 0) + 1);
    }
    const dead = [...stripComments(src).matchAll(DEAD)].length;
    if (dead) add(problems, "dead", f, `${dead} link(s) to "#" or javascript: (a control that goes nowhere; link it, make it a button, or label it as demo)`);
  }
  for (const [t, n] of longLines) if (n >= 4) add(warnings, "repeat", root, `the same sentence appears ${n}× in markup: "${t.slice(0, 60)}"`);
  for (const f of files.filter((f) => /(^|\/)data\/.*\.json$/.test(rel(f)) && !/schema\.json$/.test(f))) {
    let j; try { j = JSON.parse(readFileSync(f, "utf8")); } catch { continue; }
    for (const s of jsonStrings(j)) {
      for (const [re, label] of LEAK) if (re.test(s)) { add(problems, "leak", f, `${label}: "${s.slice(0, 70)}"`); break; }
      const g = GENERIC.exec(s); if (g) add(problems, "generic", f, `template fixture "${g[0]}"`);
    }
    for (const arr of records(j)) {
      const names = arr.map((r) => r.name ?? r.title ?? r.label);
      if (dupShare(names) > 0.25) add(problems, "repeat", f, `${Math.round(dupShare(names) * 100)}% of ${arr.length} records share a name or title`);
      const prices = arr.map((r) => r.price ?? r.amount ?? r.rate).filter((p) => p !== undefined && p !== null).map((p) => JSON.stringify(p));
      if (prices.length >= 6 && new Set(prices).size === 1) add(problems, "repeat", f, `all ${prices.length} records have the same price (${prices[0]})`);
      const desc = arr.map((r) => r.description ?? r.summary ?? r.blurb);
      if (dupShare(desc) > 0.5) add(problems, "repeat", f, `${Math.round(dupShare(desc) * 100)}% of ${arr.length} records share a description`);
    }
  }
  return { root, problems, warnings, pass: problems.length === 0 };
}

export function realismLines(r) {
  const L = [`  Content realism  ${r.pass ? "✓" : "✗"}`];
  for (const p of r.problems.slice(0, 12)) L.push(`      ✗ ${p.kind} ${p.file}: ${p.what}`);
  if (r.problems.length > 12) L.push(`      … ${r.problems.length - 12} more`);
  for (const w of r.warnings.slice(0, 6)) L.push(`      ⚠ ${w.kind} ${w.file}: ${w.what}  (warning)`);
  return L;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const args = process.argv.slice(2); const target = args.find((a) => !a.startsWith("--"));
  if (!target) { console.error("usage: node scripts/realism.mjs <project-dir> [--json]"); process.exit(2); }
  const r = realism(target); if (r.error) { console.error(`realism: ${r.error}`); process.exit(2); }
  if (args.includes("--json")) console.log(JSON.stringify(r, null, 2)); else console.log(realismLines(r).join("\n"));
  process.exit(r.pass ? 0 : 1);
}
