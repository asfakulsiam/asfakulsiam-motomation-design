#!/usr/bin/env node
// Motomation component library: reads the @motomation-component header of every file in
// skills/asfakulsiam-motomation-design/examples/components/<family>/*.tsx and writes, deterministically:
//   examples/components/README.md      the catalogue (one row per component, grouped by family)
//   data/components.csv                the same catalogue as data, for agents and scripts/search.mjs
//   registry/<id>.json + registry.json shadcn-compatible registry items, so a project can install one component:
//                                      npx shadcn@latest add https://raw.githubusercontent.com/asfakulsiam/asfakulsiam-motomation-design/main/registry/<id>.json
// `--check` fails when any generated file is stale or a header is incomplete.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SKILL = join(ROOT, "skills/asfakulsiam-motomation-design");
const LIB = join(SKILL, "examples/components");
const RAW = "https://raw.githubusercontent.com/asfakulsiam/asfakulsiam-motomation-design/main";
export const FAMILIES = { type: "Type", text: "Text effects", scroll: "Scroll", cursor: "Cursor", backgrounds: "Backgrounds", layout: "Layout and galleries", ui: "Buttons, cards and UI", micro: "Micro-interactions" };
export const KEYS = ["id", "name", "family", "tier", "deps", "what", "use-when", "avoid-when", "reduced-motion", "touch", "a11y"];

export function readHeader(src) {
  if (!/^\/\/ @motomation-component$/m.test(src)) return null;
  const h = {}; for (const k of KEYS) { const m = src.match(new RegExp(`^// ${k}: (.+)$`, "m")); if (m) h[k] = m[1].trim(); }
  return h;
}
export function collect() {
  const out = [], problems = [];
  for (const fam of Object.keys(FAMILIES)) {
    const dir = join(LIB, fam); if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir).filter((x) => x.endsWith(".tsx")).sort()) {
      const rel = relative(SKILL, join(dir, f)).split("\\").join("/"); const src = readFileSync(join(dir, f), "utf8"); const h = readHeader(src);
      if (!h) { problems.push(`${rel}: missing the // @motomation-component header`); continue; }
      for (const k of KEYS) if (!h[k]) problems.push(`${rel}: header has no "${k}"`);
      if (h.family && h.family !== fam) problems.push(`${rel}: family "${h.family}" but the file is in ${fam}/`);
      if (h.id && `${h.id}.tsx` !== f) problems.push(`${rel}: id "${h.id}" must match the file name`);
      if (h.tier && !/^[1-5]$/.test(h.tier)) problems.push(`${rel}: tier must be 1–5`);
      if (!/useReducedMotion|prefers-reduced-motion/.test(src) && !/not applicable/i.test(h["reduced-motion"] || "")) problems.push(`${rel}: no reduced-motion path in code`);
      const exp = (src.match(/^export function (\w+)/m) || [])[1]; if (!exp) problems.push(`${rel}: needs one exported function component`);
      out.push({ ...h, file: rel, export: exp, src });
    }
  }
  const seen = new Set(); for (const c of out) { if (seen.has(c.id)) problems.push(`duplicate id ${c.id}`); seen.add(c.id); }
  return { components: out, problems };
}
const csvCell = (v) => (/[",\n]/.test(v) ? `"${String(v).replace(/"/g, '""')}"` : String(v));

export function render(components) {
  const files = {};
  const sigIds = new Set(readFileSync(join(SKILL, "data/signatures.csv"), "utf8").split(/\r?\n/).slice(1).map((l) => l.split(",")[0]).filter(Boolean));
  // catalogue
  const L = [
    "# Component library", "",
    "<!-- Generated by scripts/build-components.mjs from each file's @motomation-component header. Do not edit by hand. -->", "",
    `${components.length} components across ${Object.keys(FAMILIES).length} families, written for this skill. Each is one file, typed in strict TypeScript, React only, with no other dependencies. They share a small helper file (\`_lib/motion.ts\`) for reduced motion, pointer type, viewport and scroll progress. Every component has props with sensible defaults, a reduced-motion path, a touch behaviour, and notes on when it earns its place and when it's slop.`, "",
    "**Use them like this:** a component is a starting point for a concept, not a finished design. Pick one because the Thinking Sequence asked for it, tune its props to the brief, and keep it inside the tier budget. The signature move is designed for the brief. If a component here matches it, bend the component to the concept rather than the other way round.", "",
    "**Install one into a project:**", "",
    "```bash",
    "# copy the file plus _lib/motion.ts into your components folder, or use the registry:",
    `npx shadcn@latest add ${RAW}/registry/<id>.json`,
    "```", "",
    "**See them live:** open `examples/gallery/index.html` in a browser (self-contained, no build). Toggle reduced motion in your OS to see every fallback.", "",
  ];
  for (const [fam, title] of Object.entries(FAMILIES)) {
    const rows = components.filter((c) => c.family === fam); if (!rows.length) continue;
    L.push(`## ${title}`, "", "| Component | Tier | What it does | Use when | Avoid when | Reduced motion |", "|---|---|---|---|---|---|");
    for (const c of rows) L.push(`| [\`${c.export}\`](${fam}/${c.id}.tsx)${sigIds.has(c.id) ? ` · signature \`${c.id}\`` : ""} | ${c.tier} | ${c.what} | ${c["use-when"]} | ${c["avoid-when"]} | ${c["reduced-motion"]} |`);
    L.push("");
  }
  L.push("## Anatomy of a component", "", "Every file starts with the same header, which this catalogue, `data/components.csv` and the registry are generated from. `check-repo` fails if a field is missing or the catalogue is stale.", "", "```tsx", "\"use client\";", "// @motomation-component", ...KEYS.map((k) => `// ${k}: …`), "```", "",
    "Rules for new components: one exported function component, props with defaults, no dependency beyond React unless the tier needs it, a reduced-motion path in code, cleanup of every listener and frame loop, decorative layers `aria-hidden` and `pointer-events: none`, and original code only.", "");
  files["skills/asfakulsiam-motomation-design/examples/components/README.md"] = L.join("\n");
  // data
  const cols = ["id", "name", "family", "tier", "file", "export", "what", "use_when", "avoid_when", "reduced_motion", "touch", "a11y"];
  files["skills/asfakulsiam-motomation-design/data/components.csv"] = [cols.join(","), ...components.map((c) => [c.id, c.name, c.family, c.tier, c.file.replace(/^examples\//, "examples/"), c.export, c.what, c["use-when"], c["avoid-when"], c["reduced-motion"], c.touch, c.a11y].map(csvCell).join(","))].join("\n") + "\n";
  // registry (shadcn schema): each item ships its file + the shared helper; deps are npm packages beyond react
  const helper = readFileSync(join(LIB, "_lib/motion.ts"), "utf8");
  const items = [];
  for (const c of components) {
    const npm = c.deps.split(/[ ,]+/).filter((d) => d && d !== "react");
    const item = { $schema: "https://ui.shadcn.com/schema/registry-item.json", name: c.id, type: "registry:component", title: c.name, description: c.what, dependencies: npm,
      files: [{ path: `components/motomation/${c.family}/${c.id}.tsx`, type: "registry:component", content: c.src }, { path: "components/motomation/_lib/motion.ts", type: "registry:lib", content: helper }],
      meta: { family: c.family, tier: Number(c.tier), reducedMotion: c["reduced-motion"], useWhen: c["use-when"], avoidWhen: c["avoid-when"] } };
    files[`registry/${c.id}.json`] = JSON.stringify(item, null, 2) + "\n";
    items.push({ name: c.id, type: "registry:component", title: c.name, description: c.what });
  }
  files["registry.json"] = JSON.stringify({ $schema: "https://ui.shadcn.com/schema/registry.json", name: "motomation", homepage: "https://github.com/asfakulsiam/asfakulsiam-motomation-design", items }, null, 2) + "\n";
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { components, problems } = collect();
  if (problems.length) { problems.forEach((p) => console.error(`✗ ${p}`)); process.exit(1); }
  const files = render(components);
  const regDir = join(ROOT, "registry");
  const stale = Object.entries(files).filter(([p, c]) => !existsSync(join(ROOT, p)) || readFileSync(join(ROOT, p), "utf8") !== c).map(([p]) => p);
  const orphans = existsSync(regDir) ? readdirSync(regDir).filter((f) => !files[`registry/${f}`]).map((f) => `registry/${f}`) : [];
  if (process.argv.includes("--check")) {
    if (stale.length || orphans.length) { console.error(`component catalogue is out of date (${[...stale, ...orphans].slice(0, 5).join(", ")}${stale.length + orphans.length > 5 ? ", …" : ""}). Run: node scripts/build-components.mjs`); process.exit(1); }
    console.log(`components up to date (${components.length} components)`);
  } else {
    mkdirSync(regDir, { recursive: true }); for (const o of orphans) rmSync(join(ROOT, o));
    for (const [p, c] of Object.entries(files)) writeFileSync(join(ROOT, p), c);
    console.log(`Wrote catalogue, data/components.csv and ${components.length} registry items (${stale.length} changed, ${orphans.length} removed)`);
  }
}
