#!/usr/bin/env node
// Build dist/motomation-lite.md: the core of the skill, compressed toward an 8k-token target, for small-context tools
// (custom instructions, rules files, v0/Bolt prompts). The full edition stays in dist/motomation-design.md.
// The target belongs to this build step only. The full skill has no token budget and never reads this one: the build
// reads the full skill and compresses it. Over the target, whole sections are dropped (DROP_ORDER) and named at the top.
// Deterministic: same sources → byte-identical output. `--check` fails if the file is stale.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseCSV } from "../skills/asfakulsiam-motomation-design/scripts/lib.mjs";
import { cli } from "../skills/asfakulsiam-motomation-design/scripts/lib.mjs";
cli("build-lite", "Usage: node scripts/build-lite.mjs [--check]", { check: "bool" }, null, { pos: [0, 0] });

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SKILL = join(ROOT, "skills/asfakulsiam-motomation-design");
const TOKEN_BUDGET = 8000; // lite size target (a goal for this build step, not a limit on the skill)
// Conservative estimate without a tokenizer dependency: ~3.5 characters per token for English Markdown
// (real tokenizers average ~4, so this over-counts).
export const estimateTokens = (s) => Math.ceil(s.length / 3.5);

const read = (p) => readFileSync(join(SKILL, p), "utf8");
const csv = (f) => parseCSV(read(`data/${f}.csv`));
const unmark = (t) => t.replace(/<!--rule:[a-z_]+-->([\s\S]*?)<!--\/rule-->/g, "$1"); // keep the rendered rule text
const noFrontMatter = (t) => t.replace(/^---\n[\s\S]*?\n---\n/, "");
const demote = (t) => t.replace(/^(#{1,5}) /gm, "#$1 ");
/** Sections of a Markdown file between `## ` headings, keyed by heading text. */
const sections = (t) => {
  const out = []; let cur = { head: "", body: [] };
  for (const line of t.split("\n")) {
    if (/^## /.test(line)) { out.push(cur); cur = { head: line.slice(3).trim(), body: [line] }; } else cur.body.push(line);
  }
  out.push(cur);
  return out.map((s) => ({ head: s.head, text: s.body.join("\n").trim() }));
};
const pickSections = (t, keep) => sections(t).filter((s) => keep(s.head)).map((s) => s.text).join("\n\n");

const version = read("VERSION").trim();
// "Compose, extend, or invent" points into this skill's examples/ and component library, which a chat tool doesn't have either.
const dropSub = (t, re) => t.replace(new RegExp(`^### ${re.source}[\\s\\S]*?(?=^#{2,3} )`, "m"), "");
// The summary's steps 1–7 are printed in full under "Thinking Sequence (steps)"; only its Step 0 line stays here.
const onlyStep0 = (t) => t.replace(/(^## The Thinking Sequence[^\n]*\n)([\s\S]*?)(?=^## )/m, (_, h, body) => h + body.split("\n").filter((l) => !/^[1-7]\. /.test(l)).join("\n"));
const skill = onlyStep0(dropSub(unmark(noFrontMatter(read("SKILL.md"))), /Compose, extend, or invent/))
  .replace(/^- After delivery, log the run to the user-level memory[^\n]*\n/m, ""); // the memory log needs a shell and a file system
const DROP_FROM_SKILL = [/^Router/, /^Tools inside this skill/, /^Commands/, /^Default flow/]; // file loading, scripts, slash commands and the file-by-file flow map don't exist in a chat tool; the sequence summary and steps below carry the order
const parts = [
  `# Motomation Design v${version}: lite edition`,
  "",
  "> By asfakulsiam · MIT · https://github.com/asfakulsiam/asfakulsiam-motomation-design",
  "> Generated by `scripts/build-lite.mjs`. Do not edit by hand. For small-context tools; the full edition is `dist/motomation-design.md`.",
  "> File paths below point into the full skill. Without them, follow the summaries here and use the short lists at the end as fuel, not a menu: derive from the brief, with the lists as reference and constraint, never the first row.",
  "",
  demote(pickSections(skill, (h) => !DROP_FROM_SKILL.some((re) => re.test(h)))),
  "",
  "## Without a shell",
  "",
  "You can't run the collision engine, memory or gate here. So write the product contract first, take the structure from it and from research, use the lists below only as optional prompts (check each archetype's \"fails when\"), state why, and don't repeat the previous project's picks without a reason. Do the Delivery Gate by reading your own code: contrast per surface, overflow at 375px, long words at 375px, and text visible under reduced motion. Write the stamp's gate fields as `not measured`, never as numbers you didn't measure.",
  "",
  "## Thinking Sequence (steps)",
  "",
  demote(pickSections(unmark(read("thinking/sequence.md")).replace(/^\*\*When the draw doesn't fit\.\*\*[^\n]*\n\n/m, "") // collide.mjs draws need a shell
     .replace(/^\*\*Reuse across projects\.\*\*[^\n]*\n\n/m, "") // the cross-project memory log needs a shell too
     .replace(/^\*\*WRONG \/ RIGHT\*\*[^\n]*\n\n(?:- [^\n]*\n)+\n/m, "") // a secondary worked example; the rule above it and its test stay
     .replace(/^A \*\*production template\*\* build that has a server also requires[^\n]*\n\n(?:- [^\n]*\n)+\n/m, "") // the server-template file list; templates/TEMPLATE.md has it
     .replace(/^\*\*Checkpoint [4-6]: [^\n]*\n\n?/gm, "") // checkpoints 4–6 are summarised in SKILL.md's checkpoint block above
     .replace(/^[13]\. \*\*(?:Memory|Earlier builds, measured)[^\n]*\n/gm, ""), // memory.mjs and originality.mjs need a shell
     (h) => /^[1-7]\. /.test(h))), // Step 0 (Stack) rides in the SKILL.md summary above
  "",
  demote(pickSections(unmark(read("gates/delivery-gate.md")), (h) => /^Part [23]/.test(h))),
  "",
  "## Short lists",
  "",
  "Archetypes (optional; skip when the contract sets the structure): " + csv("archetypes").map((r) => `${r.name} (${r.shape}; fails when ${r.fails_when})`).join("; ") + ".",
  "",
  "Mutations (optional, never on a rule that protects a journey): " + csv("mutations").map((r) => `${r.name}: ${r.operator}`).join("; ") + ".",
  "",
  "Signatures (optional, at most one; none is valid): " + csv("signatures").map((r) => `${r.name} [T${r.tier}]`).join("; ") + ".",
  "",
];
const full = parts.join("\n").replace(/\n{3,}/g, "\n\n").trim() + "\n";
// Over the target, drop whole ### sections in this order (the ones a chat tool needs least first) until it fits, and
// say so at the top. Nothing in the full skill is shortened to fit.
const DROP_ORDER = [/^Standards, heuristics and house style/, /^Routes: full and light/, /^When to use the short route/, /^Motion tiers/, /^House style defaults/, /^Part 3: Craft checklist/];
const dropSection = (t, re) => { let name = null; const u = t.replace(/^### ([^\n]*)\n[\s\S]*?(?=^#{2,3} |(?![\s\S]))/gm, (m, h) => (name === null && re.test(h) ? ((name = h.replace(/\s*\(.*\)$/, "")), "") : m)); return { text: u, name }; };
const withNote = (t, dropped) => dropped.length ? t.replace(/^(# [^\n]*\n)/, `$1\nLite edition. Full version at the repo. Dropped: ${dropped.join(", ")}.\n`) : t;
let body = full; const dropped = [];
for (const re of DROP_ORDER) { if (estimateTokens(withNote(body, dropped)) <= TOKEN_BUDGET) break; const d = dropSection(body, re); if (d.name) { body = d.text; dropped.push(d.name); } }
let out = withNote(body, dropped).replace(/\n{3,}/g, "\n\n");
const tokens = estimateTokens(out);
if (tokens > TOKEN_BUDGET) console.warn(`motomation-lite.md is ~${tokens} tokens, still over the ${TOKEN_BUDGET}-token target after dropping ${dropped.length} section(s); add to DROP_ORDER in scripts/build-lite.mjs.`);

const target = join(ROOT, "dist/motomation-lite.md");
// The README states the lite size between markers. This script writes it, so the number is generated, never typed:
// <!-- lite-tokens -->about 7.8k tokens<!-- /lite-tokens -->  (rounded to 0.1k, from the same estimate as the budget)
const README = join(ROOT, "README.md");
const claim = `<!-- lite-tokens -->about ${(tokens / 1000).toFixed(1)}k tokens<!-- /lite-tokens -->`;
const MARK = /<!-- lite-tokens -->[\s\S]*?<!-- \/lite-tokens -->/;
const readme = readFileSync(README, "utf8");
if (!MARK.test(readme)) { console.error("README.md has no <!-- lite-tokens --> marker for the lite size."); process.exit(1); }
if (process.argv.includes("--check")) {
  let current = ""; try { current = readFileSync(target, "utf8"); } catch {}
  if (current !== out) { console.error("dist/motomation-lite.md is out of date. Run: node scripts/build-lite.mjs"); process.exit(1); }
  const said = readme.match(MARK)[0];
  if (said !== claim) { console.error(`README says "${said.replace(/<!--[^>]*-->/g, "")}" but the lite is ~${tokens} tokens ("${claim.replace(/<!--[^>]*-->/g, "")}"). Run: node scripts/build-lite.mjs`); process.exit(1); }
  console.log(`lite is up to date (~${tokens} tokens, target ${TOKEN_BUDGET}${dropped.length ? `, dropped: ${dropped.join(", ")}` : ""})`);
} else {
  mkdirSync(join(ROOT, "dist"), { recursive: true });
  writeFileSync(target, out);
  if (readme.match(MARK)[0] !== claim) writeFileSync(README, readme.replace(MARK, claim));
  console.log(`Wrote dist/motomation-lite.md (${(out.length / 1024).toFixed(1)} KB, ~${tokens} tokens estimated, target ${TOKEN_BUDGET}${dropped.length ? `; dropped: ${dropped.join(", ")}` : ""})`);
}
