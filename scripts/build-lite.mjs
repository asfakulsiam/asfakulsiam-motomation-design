#!/usr/bin/env node
// Build dist/motomation-lite.md: the core of the skill in under 8k tokens, for small-context tools
// (custom instructions, rules files, v0/Bolt prompts). The full edition stays in dist/motomation-design.md.
// Deterministic: same sources → byte-identical output. `--check` fails if the file is stale or over budget.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseCSV } from "../skills/asfakulsiam-motomation-design/scripts/lib.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SKILL = join(ROOT, "skills/asfakulsiam-motomation-design");
const TOKEN_BUDGET = 8000;
// Conservative estimate without a tokenizer dependency: ~3.5 characters per token for English Markdown
// (real tokenizers average ~4, so this over-counts).
export const estimateTokens = (s) => Math.ceil(s.length / 3.5);

const read = (p) => readFileSync(join(SKILL, p), "utf8");
const csv = (f) => parseCSV(read(`data/${f}.csv`));
const unmark = (t) => t.replace(/<!--rule:[a-z_]+-->([\s\S]*?)<!--\/rule-->/g, "$1"); // keep the rendered rule text
const noFrontMatter = (t) => t.replace(/^---\n[\s\S]*?\n---\n/, "");
const demote = (t) => t.replace(/^(#{1,5}) /gm, "#$1 ");
/** Sections of a Markdown file between `## ` headings, keyed by heading text. */
const sections = (t) => {
  const out = []; let cur = { head: "", body: [] };
  for (const line of t.split("\n")) {
    if (/^## /.test(line)) { out.push(cur); cur = { head: line.slice(3).trim(), body: [line] }; } else cur.body.push(line);
  }
  out.push(cur);
  return out.map((s) => ({ head: s.head, text: s.body.join("\n").trim() }));
};
const pickSections = (t, keep) => sections(t).filter((s) => keep(s.head)).map((s) => s.text).join("\n\n");

const version = read("VERSION").trim();
const skill = unmark(noFrontMatter(read("SKILL.md")));
const DROP_FROM_SKILL = [/^Router/, /^Tools inside this skill/]; // file loading and scripts don't exist in a chat tool
const parts = [
  `# Motomation Design v${version}: lite edition`,
  "",
  "> By asfakulsiam · MIT · https://github.com/asfakulsiam/asfakulsiam-motomation-design",
  "> Generated by `scripts/build-lite.mjs`. Do not edit by hand. For small-context tools; the full edition is `dist/motomation-design.md`.",
  "> File paths below point into the full skill. Without them, follow the summaries here and pick from the short lists at the end, deliberately, never the first row.",
  "",
  demote(pickSections(skill, (h) => !DROP_FROM_SKILL.some((re) => re.test(h)))),
  "",
  "## Without a shell",
  "",
  "You can't run the collision engine, memory or gate here. So pick one archetype, one mutation and one signature from the lists below, state why, and never reuse the previous project's picks. Do the Delivery Gate by reading your own code: contrast per surface, overflow at 375px, long words at 375px, and text visible under reduced motion. Write the stamp's gate fields as `not measured`, never as numbers you didn't measure.",
  "",
  "## Thinking Sequence (steps)",
  "",
  demote(pickSections(unmark(read("thinking/sequence.md")), (h) => /^\d\. /.test(h))),
  "",
  demote(pickSections(unmark(read("gates/delivery-gate.md")), (h) => /^Part [23]/.test(h))),
  "",
  "## Short lists",
  "",
  "Archetypes: " + csv("archetypes").map((r) => `${r.name} (${r.shape})`).join("; ") + ".",
  "",
  "Mutations: " + csv("mutations").map((r) => `${r.name}: ${r.operator}`).join("; ") + ".",
  "",
  "Signatures: " + csv("signatures").map((r) => `${r.name} [T${r.tier}]: ${r.one_line}`).join("; ") + ".",
  "",
];
let out = parts.join("\n").replace(/\n{3,}/g, "\n\n").trim() + "\n";
const tokens = estimateTokens(out);
if (tokens > TOKEN_BUDGET) { console.error(`motomation-lite.md is ~${tokens} tokens, over the ${TOKEN_BUDGET} budget. Trim the selection in scripts/build-lite.mjs.`); process.exit(1); }

const target = join(ROOT, "dist/motomation-lite.md");
if (process.argv.includes("--check")) {
  let current = ""; try { current = readFileSync(target, "utf8"); } catch {}
  if (current !== out) { console.error("dist/motomation-lite.md is out of date. Run: node scripts/build-lite.mjs"); process.exit(1); }
  console.log(`lite is up to date (~${tokens} tokens, budget ${TOKEN_BUDGET})`);
} else {
  mkdirSync(join(ROOT, "dist"), { recursive: true });
  writeFileSync(target, out);
  console.log(`Wrote dist/motomation-lite.md (${(out.length / 1024).toFixed(1)} KB, ~${tokens} tokens estimated, budget ${TOKEN_BUDGET})`);
}
