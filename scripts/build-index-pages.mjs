#!/usr/bin/env node
// Builds the two folder index pages the docs site links to but GitHub Pages had no file for (v2.5.0, C11):
//   docs/templates/index.html → /templates/   every page template and Tier 5 film, linked
//   docs/plain/index.html     → /plain/       the five plain (no-React) components, CSS and Tailwind variants linked
// Static HTML, no JavaScript, no build tools: generated from the template headers (build-templates.mjs collect and
// collectFilms) and vendor/plain/top5.json. pages.yml copies both into the site; check-repo fails if either is stale.
//   node scripts/build-index-pages.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { cli, parseCSV } from "../skills/asfakulsiam-motomation-design/scripts/lib.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const CSS = `:root{color-scheme:light dark;--ink:#16140f;--ground:#f4f1ea;--muted:#55504a;--line:#d6d0c4;--accent:#8a2b12}
@media (prefers-color-scheme:dark){:root{--ink:#f1ede4;--ground:#14130f;--muted:#b4ada1;--line:#3a3730;--accent:#f0a07a}}
*{box-sizing:border-box}body{margin:0;background:var(--ground);color:var(--ink);font:400 1rem/1.55 ui-sans-serif,system-ui,-apple-system,"Segoe UI",sans-serif}
main{max-width:68rem;margin:0 auto;padding:clamp(1.5rem,5vw,4rem) clamp(1rem,4vw,2.5rem)}
.eyebrow{font:600 .8rem/1 ui-monospace,SFMono-Regular,Menlo,monospace;letter-spacing:.08em;text-transform:uppercase;color:var(--muted);margin:0 0 1rem}
h1{font:700 clamp(2.4rem,7vw,5.5rem)/.95 ui-serif,Georgia,serif;letter-spacing:-.02em;margin:0 0 1.25rem;max-width:14ch}
.lede{font-size:1.15rem;max-width:44rem;color:var(--muted);margin:0 0 2.5rem}
h2{font:700 1.4rem/1.2 ui-serif,Georgia,serif;margin:3rem 0 1rem}
ul.list{list-style:none;margin:0;padding:0;border-top:1px solid var(--line)}
ul.list li{display:grid;grid-template-columns:minmax(12rem,1fr) 2fr;gap:.5rem 2rem;padding:1rem 0;border-bottom:1px solid var(--line)}
@media (max-width:40rem){ul.list li{grid-template-columns:1fr}}
a{color:var(--accent);text-underline-offset:.18em}a:focus-visible{outline:3px solid var(--accent);outline-offset:3px}
.name{font-weight:650}.meta{font:400 .85rem/1.4 ui-monospace,SFMono-Regular,Menlo,monospace;color:var(--muted);margin:.25rem 0 0}
.what{margin:0}nav.top{margin:0 0 2.5rem;font-size:.95rem}nav.top a{margin-right:1.25rem}`;
const page = (title, desc, eyebrow, h1, lede, body) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<meta name="motomation-index" content="generated by scripts/build-index-pages.mjs">
<link rel="icon" href="data:,">
<style>${CSS}</style>
</head>
<body>
<main>
<nav class="top" aria-label="Motomation Design"><a href="../">Components</a><a href="../gallery/">Gallery</a><a href="../templates/">Templates</a><a href="../plain/">Plain variants</a><a href="https://github.com/asfakulsiam/asfakulsiam-motomation-design">Repository</a></nav>
<p class="eyebrow">${esc(eyebrow)}</p>
<h1>${esc(h1)}</h1>
<p class="lede">${lede}</p>
${body}
</main>
</body>
</html>
`;

export async function render() {
  const { collect, collectFilms } = await import("./build-templates.mjs");
  const { templates } = await collect(); const films = collectFilms();
  const li = (href, name, meta, what) => `<li><div><a class="name" href="${esc(href)}">${esc(name)}</a><p class="meta">${esc(meta)}</p></div><p class="what">${esc(what)}</p></li>`;
  const tBody = `<h2>Page templates (${templates.length})</h2>
<ul class="list">
${templates.map((t) => li(`${t.id}.html`, t.name, `${t.kind} · tier ${t.tier} · ${t.archetype}`, t.what)).join("\n")}
</ul>${films.length ? `
<h2>Tier 5 films (${films.length})</h2>
<ul class="list">
${films.map((f) => li(`${f.id}/`, f.name, `tier ${f.tier} · ${f.archetype}${f.frames ? ` · ${f.frames.desktop.frames} frames` : ""}`, f.what)).join("\n")}
</ul>` : ""}`;
  const templatesHtml = page(`Motomation templates · ${templates.length + films.length} pages`, `${templates.length} page templates and ${films.length} Tier 5 films from the Motomation Design skill, each gated and stamped.`,
    "Motomation Design · templates", "Page templates", `${templates.length} whole pages built only from the library's sections, plus ${films.length} scroll-as-film pages. Each one passed the Delivery Gate and carries its stamp in the source.`, tBody);
  const top = JSON.parse(readFileSync(join(ROOT, "vendor/plain/top5.json"), "utf8")).components;
  const comp = new Map(parseCSV(readFileSync(join(ROOT, "skills/asfakulsiam-motomation-design/data/components.csv"), "utf8")).map((r) => [r.id, r]));
  const what = (id) => comp.get(id)?.what || id;
  const pBody = `<h2>The five (ranked by use)</h2>
<ul class="list">
${top.map((c, i) => `<li><div><span class="name">${i + 1}. ${esc(comp.get(c.id)?.name || c.id)}</span><p class="meta">${esc(c.react.replace("skills/asfakulsiam-motomation-design/", ""))}</p></div><p class="what">${esc(what(c.id))}<br><a href="${esc(c.id)}/plain.html">CSS + HTML</a> · <a href="${esc(c.id)}/tailwind.html">Tailwind</a> · <a href="https://github.com/asfakulsiam/asfakulsiam-motomation-design/tree/main/vendor/plain/${esc(c.id)}">source</a></p></li>`).join("\n")}
</ul>`;
  const plainHtml = page("Motomation plain variants · top 5 components without React", "The five most-used Motomation components as dependency-free CSS + HTML and Tailwind variants.",
    "Motomation Design · vendor/plain", "Plain variants", "The library is React-first. The five components the most sections and templates use also ship without React: a CSS + HTML variant and a Tailwind variant, both running the same dependency-free script.", pBody);
  return { "docs/templates/index.html": templatesHtml, "docs/plain/index.html": plainHtml };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const a = cli("build-index-pages", "Usage: node scripts/build-index-pages.mjs [--check]", { check: "bool" }, null, { pos: [0, 0] });
  const files = await render();
  const stale = Object.entries(files).filter(([p, c]) => !existsSync(join(ROOT, p)) || readFileSync(join(ROOT, p), "utf8") !== c).map(([p]) => p);
  if (a.check) { if (stale.length) { console.error(`stale: ${stale.join(", ")}. Run: node scripts/build-index-pages.mjs`); process.exit(1); } console.log("index pages up to date"); process.exit(0); }
  for (const [p, c] of Object.entries(files)) { mkdirSync(dirname(join(ROOT, p)), { recursive: true }); writeFileSync(join(ROOT, p), c); }
  console.log(`Wrote ${Object.keys(files).join(", ")}`);
}
